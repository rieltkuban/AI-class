export interface RunFacts {
  contour: Contour;
  cycleDays: CycleDays;
  /** Порядок выручки, не точное число. */
  revenueBand: string;
  /** Цена суток, посчитанная кодом. Модель числа не считает. */
  dayCost: string | null;
  /** Числа посетителя, уровень figures. */
  figures?: { period1: number; period2: number; metric: string };
  /** Текст посетителя, уровень fragment. Уже обрезан и очищен. */
  fragment?: string;
  /** Обезличенный набор, уровень none. */
  sample?: string;
}

/** Пользовательская часть промпта. Данные обёрнуты явными маркерами. */
export function buildUserPrompt(facts: RunFacts): string {
  const lines: string[] = [
    'ДАННЫЕ-НАЧАЛО',
    `Контур решения: ${CONTOUR_LABEL[facts.contour]}`,
    `Цикл решения: ${CYCLE_LABEL[facts.cycleDays]}`,
    `Порядок годовой выручки: ${facts.revenueBand}`,
  ];

  if (facts.dayCost) {
    lines.push(`Цена одних суток задержки, посчитанная заранее: ${facts.dayCost}`);
  }

  if (facts.figures) {
    lines.push(
      'Показатель, который назвал руководитель:',
      `  метрика: ${facts.figures.metric}`,
      `  предыдущий период: ${facts.figures.period1}`,
      `  текущий период: ${facts.figures.period2}`,
    );
  }

  if (facts.sample) {
    lines.push('Обезличенный набор по этому контуру:', facts.sample);
  }

  if (facts.fragment) {
    lines.push('Фрагмент, который приложил руководитель:', facts.fragment);
  }

  lines.push('ДАННЫЕ-КОНЕЦ');
  return lines.join('\n');
}

/** Признаки утечки системного промпта в ответе. Проверяется перед показом. */
const LEAK_MARKERS = [
  'Правила, которые нельзя нарушать',
  'ДАННЫЕ-НАЧАЛО',
  'ДАННЫЕ-КОНЕЦ',
  'Ты аналитик, который готовит вывод',
  'Ты оппонент',
  'системный промпт',
];

export function looksLikeLeak(text: string): boolean {
  const lower = text.toLowerCase();
  return LEAK_MARKERS.some((marker) => lower.includes(marker.toLowerCase()));
}
